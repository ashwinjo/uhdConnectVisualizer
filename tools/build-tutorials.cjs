/* Bundles docs/tutorials/*.md into tutorials.js so the page can show them with no
 * server. index.html is opened over file://, where fetch() of a sibling file is
 * blocked, so the markdown has to ship as JavaScript.
 *
 *   node tools/build-tutorials.cjs           # write tutorials.js
 *   node tools/build-tutorials.cjs --check   # exit 1 if it is out of date
 *
 * Run it after editing anything in docs/tutorials.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'docs', 'tutorials');
const OUT = path.join(ROOT, 'tutorials.js');

/* README first, then the numbered pages in order. */
function order(a, b) {
  if (a === 'README.md') return -1;
  if (b === 'README.md') return 1;
  return a.localeCompare(b);
}

/* Must match TUT_SLUG in app.js: headings become ids by the same rule. */
const slug = s => s.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/\s+/g, '-');

/* Sidebar sections are the h2s, but ids are numbered across *all* headings the way
 * mdToHtml numbers them, so a repeated h3 cannot shift an h2's anchor. */
function headings(md) {
  const seen = new Map();
  return [...md.matchAll(/^(#{1,6}) (.+)$/gm)].map(m => {
    const text = m[2].trim();
    const base = slug(text);
    const n = (seen.get(base) || 0) + 1;
    seen.set(base, n);
    return { level: m[1].length, text, anchor: n === 1 ? base : base + '-' + n };
  });
}

function build() {
  const files = fs.readdirSync(SRC).filter(f => f.endsWith('.md')).sort(order);
  const pages = files.map(file => {
    const md = fs.readFileSync(path.join(SRC, file), 'utf8');
    const h1 = (md.match(/^# (.+)$/m) || [, file])[1].trim();
    const toc = headings(md).filter(h => h.level === 2).map(h => ({ text: h.text, anchor: h.anchor }));
    return {
      id: file.replace(/\.md$/, ''),
      file,
      title: h1,
      nav: file === 'README.md' ? 'Start here' : h1,
      toc,
      md
    };
  });

  const body = JSON.stringify(pages, null, 1).replace(/<\/script/gi, '<\\/script');
  return '/* GENERATED by tools/build-tutorials.cjs from docs/tutorials/*.md.\n'
    + ' * Do not edit: change the markdown and re-run the script. */\n'
    + 'window.TUTORIALS = ' + body + ';\n';
}

const text = build();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('tutorials.js is out of date. Run: node tools/build-tutorials.cjs');
    process.exit(1);
  }
  console.log('tutorials.js is up to date');
  process.exit(0);
}

fs.writeFileSync(OUT, text);
const pages = JSON.parse(text.slice(text.indexOf('=') + 1, -2));
console.log('wrote tutorials.js: ' + pages.length + ' pages, '
  + pages.reduce((n, p) => n + p.toc.length, 0) + ' sections, '
  + (Buffer.byteLength(text) / 1024).toFixed(1) + ' KB');
